'use strict';

const fs = require('fs');
const Vote = require('../models/Vote');
const VotingToken = require('../models/VotingToken');
const Voter = require('../models/Voter');
const { verifyVotingToken, markTokenAsUsed, VERIFY_RESULT } = require('../services/tokenVerificationService');
const { ensureKeyFiles, getKeyPairPaths } = require('../crypto/keyManager');
const { encryptVotePayload, generateReceipt, storeVote } = require('../services/voteService');

/**
 * castVote
 * --------
 * Part 6 (Tanaya): Vote Submission API + SHA-256 Receipt Generation
 *
 * Request Body:
 *  - token: string (raw hex voting token)
 *  - signature: string (base64 RSA signature generated by Part 3)
 *  - candidateId: string (candidate choice)
 *  - votePayload: object (optional, specific ballot metadata)
 *
 * Pipeline:
 *  1. Validate required inputs
 *  2. Load trusted server RSA public key (server-side, never from client)
 *  3. Verify token and RSA signature via Member 4's verifyVotingToken (3-stage check)
 *  4. Verify voter eligibility if authenticated voter session exists
 *  5. Encrypt vote payload using Member 5's AES-256-GCM
 *  6. Compute SHA-256 receipt hash matching Member 7's verification formula
 *  7. Atomically mark voting token as used (prevents concurrent replay attacks)
 *  8. Persist encrypted vote record with authTag using storeVote
 *     (includes idempotent recovery: guards against rollback race on timeout)
 *  9. Update voter's hasVoted flag
 * 10. Return 201 Created with receiptHash and voteId
 */
const castVote = async (req, res, next) => {
  try {
    const { token, signature, candidateId, votePayload } = req.body;

    // ── Step 1: Input validation ─────────────────────────────────────────────
    if (!token || !candidateId) {
      return res.status(400).json({
        message: 'Voting token and candidateId are required fields',
      });
    }

    if (!signature) {
      return res.status(400).json({
        message: 'Voting token signature is required',
      });
    }

    // ── Step 2: Load trusted server public key ────────────────────────────────
    // Never trust a client-supplied public key; always load server key pair
    ensureKeyFiles();
    const { publicKeyPath } = getKeyPairPaths();
    const publicKey = fs.readFileSync(publicKeyPath, 'utf8');

    // ── Step 3: Member 4 Token & Signature Verification ──────────────────────
    const { code, tokenRecord, tokenHash } = await verifyVotingToken(token, signature, publicKey);

    switch (code) {
      case VERIFY_RESULT.VALID:
        break; // Passed all 3 stages: signature valid, exists in DB, unused

      case VERIFY_RESULT.MISSING_FIELDS:
        return res.status(400).json({
          message: 'Token, signature, and publicKey are required',
          code,
        });

      case VERIFY_RESULT.SIGNATURE_INVALID:
        return res.status(401).json({
          message: 'Token rejected: RSA signature is invalid or token was tampered with',
          code,
        });

      case VERIFY_RESULT.TOKEN_NOT_FOUND:
        return res.status(401).json({
          message: 'Token rejected: this voting token was not issued by our system',
          code,
        });

      case VERIFY_RESULT.TOKEN_ALREADY_USED:
        return res.status(409).json({
          message: 'Token rejected: this voting token has already been used (replay attack prevented)',
          code,
          usedAt: tokenRecord ? tokenRecord.usedAt : null,
        });

      default:
        return res.status(500).json({
          message: 'An internal error occurred during token verification',
          code: VERIFY_RESULT.INTERNAL_ERROR,
        });
    }

    // ── Step 4: Voter session eligibility check ──────────────────────────────
    let voter = null;
    if (req.user && req.user.sub) {
      voter = await Voter.findById(req.user.sub);
      if (voter && voter.hasVoted) {
        return res.status(403).json({
          message: 'Voter cannot vote again: ballot has already been submitted for this account',
        });
      }
    }

    // ── Step 5: Member 5 AES-256-GCM Vote Encryption ─────────────────────────
    const secretKey = process.env.AES_SECRET_KEY;
    if (!secretKey || typeof secretKey !== 'string' || !/^[0-9a-fA-F]{64}$/.test(secretKey)) {
      return res.status(500).json({
        message: 'Internal server configuration error: AES key must be a 64-character hexadecimal string',
      });
    }

    const payloadToEncrypt = votePayload || { candidateId };
    let encryptionResult;
    try {
      encryptionResult = encryptVotePayload(payloadToEncrypt, secretKey);
    } catch (encError) {
      return res.status(500).json({
        message: 'Failed to encrypt vote payload',
        error: encError.message,
      });
    }

    const { encryptedVote, iv, authTag } = encryptionResult;

    // ── Step 6: Generate SHA-256 Receipt Hash ────────────────────────────────
    // Formula: SHA-256(encryptedVote + ":" + iv + ":" + authTag)
    // Matches Member 7's verifyVoteReceipt in backend/services/verificationService.js
    const receiptHash = generateReceipt(encryptedVote, iv, authTag);

    // ── Step 7: Atomic Token Consumption ─────────────────────────────────────
    // Atomically consumes token; prevents concurrent race conditions
    const consumed = await markTokenAsUsed(tokenHash);
    if (!consumed) {
      return res.status(409).json({
        message: 'Token was already marked as used — double-vote attempt detected',
        code: VERIFY_RESULT.TOKEN_ALREADY_USED,
      });
    }

    // ── Step 8: Persist Vote with AuthTag in MongoDB ─────────────────────────
    // Idempotent persistence & rollback-race prevention:
    // If storeVote throws an error (e.g. socket timeout, network disconnection),
    // the write may have succeeded in MongoDB. Verify before rolling back token state.
    let vote = null;
    try {
      const stored = await storeVote({
        encryptedVote,
        iv,
        authTag,
        receiptHash,
      });
      vote = stored.vote;
    } catch (dbError) {
      // Check if the vote actually exists in MongoDB despite the error
      let existingVote = null;
      let checkFailed = false;
      try {
        existingVote = await Vote.findOne({ receiptHash });
      } catch (checkErr) {
        checkFailed = true;
        console.error('Warning: Unable to verify vote persistence status after DB error:', checkErr.message);
      }

      if (existingVote) {
        // Vote was persisted despite the error: preserve consumed token state idempotently
        vote = existingVote;
      } else if (!checkFailed) {
        // Confirmed that vote does not exist in DB: safely rollback token consumption
        try {
          await VotingToken.updateOne(
            { tokenHash },
            { $set: { used: false }, $unset: { usedAt: 1 } }
          );
        } catch (rollbackError) {
          console.error('Critical: Failed to rollback token consumption after verified DB failure:', rollbackError.message);
        }

        return res.status(500).json({
          message: 'Failed to record vote in database',
          error: dbError.message,
        });
      } else {
        // Vote state is uncertain: do NOT blindly reset token to avoid double-voting risk
        return res.status(500).json({
          message: 'Database error occurred; vote state is uncertain. Please contact the election administrator.',
          error: dbError.message,
        });
      }
    }

    // ── Step 9: Update voter's hasVoted flag ─────────────────────────────────
    if (voter) {
      try {
        voter.hasVoted = true;
        await voter.save();
      } catch (voterErr) {
        console.error('Non-fatal: Failed to update voter hasVoted status:', voterErr.message);
      }
    }

    // ── Step 10: Return Success Response ────────────────────────────────────
    return res.status(201).json({
      message: 'Vote cast successfully',
      receiptHash,
      voteId: vote._id,
    });
  } catch (error) {
    next(error);
  }
};

module.exports = { castVote };
