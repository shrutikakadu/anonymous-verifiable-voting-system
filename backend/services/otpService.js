const bcrypt = require('bcryptjs');
const nodemailer = require('nodemailer');
const { generateOTP } = require('../utils/generateOTP');
const { isValidEmail } = require('../utils/validation');
const { saveOTPState } = require('../utils/saveOTPState');

const OTP_LIFETIME_MS = 5 * 60 * 1000;
const OTP_COOLDOWN_MS = 60 * 1000;
const OTP_MAX_ATTEMPTS = 5;

const getEmailConfig = () => {
  const user = (process.env.OTP_EMAIL || '').trim();
  const pass = (process.env.OTP_EMAIL_PASSWORD || '').trim();
  if (!isValidEmail(user) || !pass || user === 'your_email@example.com'
      || pass === 'your_email_app_password') {
    const error = new Error('OTP email delivery is not configured');
    error.code = 'OTP_EMAIL_NOT_CONFIGURED';
    throw error;
  }
  return { user, pass };
};

const sendOTP = async (email, otpCode, purpose) => {
  const auth = getEmailConfig();

  const transporter = nodemailer.createTransport({
    service: 'gmail',
    auth,
    connectionTimeout: 5000,
    greetingTimeout: 5000,
    socketTimeout: 10000,
  });

  const info = await transporter.sendMail({
    from: auth.user,
    to: email,
    subject: purpose === 'registration' ? 'Verify your voter registration' : 'Your voter login code',
    text: `Your ${purpose} verification code is ${otpCode}. It expires in 5 minutes. Do not share this code.`,
  });
  if (!info || !Array.isArray(info.accepted)
      || !info.accepted.some((recipient) => String(recipient).toLowerCase() === email.toLowerCase())) {
    const error = new Error('OTP email was not accepted for delivery');
    error.code = 'OTP_EMAIL_REJECTED';
    throw error;
  }
};

const createOTPForVoter = async (voter, purpose) => {
  if (!['registration', 'login'].includes(purpose)) {
    throw new Error('Invalid OTP purpose');
  }
  if (voter.otpLastSentAt && voter.otpLastPurpose === purpose
      && Date.now() - new Date(voter.otpLastSentAt).getTime() < OTP_COOLDOWN_MS) {
    const error = new Error('Please wait 60 seconds before requesting another OTP');
    error.status = 429;
    throw error;
  }

  const previous = {
    otpLastSentAt: voter.otpLastSentAt || null,
    otpLastPurpose: voter.otpLastPurpose || null,
  };
  // Missing configuration must not create an unusable challenge or log a code.
  getEmailConfig();
  const code = generateOTP(6);
  voter.otpHash = await bcrypt.hash(code, 10);
  voter.otpPurpose = purpose;
  voter.otpExpiresAt = new Date(Date.now() + OTP_LIFETIME_MS);
  voter.otpLastSentAt = new Date();
  voter.otpLastPurpose = purpose;
  voter.otpAttempts = 0;
  if (purpose === 'login') voter.otpVerified = false;
  if (!(await saveOTPState(voter, previous))) {
    const error = new Error('Please wait 60 seconds before requesting another OTP');
    error.status = 429;
    throw error;
  }
  const challengeHash = voter.otpHash;
  try {
    await sendOTP(voter.email, code, purpose);
  } catch (error) {
    voter.otpHash = null;
    voter.otpPurpose = null;
    voter.otpExpiresAt = null;
    // Do not clear a challenge generated by a more recent request.
    await saveOTPState(voter, { otpHash: challengeHash });
    throw error;
  }
};

module.exports = { sendOTP, createOTPForVoter, getEmailConfig, OTP_MAX_ATTEMPTS, OTP_COOLDOWN_MS };
